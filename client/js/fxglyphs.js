const cache = new Map();
const darken = (h, k) => { const n = parseInt(h.slice(1), 16); const f = (v) => Math.max(0, Math.round(v * k)).toString(16).padStart(2, '0'); return '#' + f((n >> 16) & 255) + f((n >> 8) & 255) + f(n & 255); };
// returns a canvas with the glyph rendered at 1px per cell (+1px outline border)
export function glyphSprite(key, main, light, outline = true) {
  const id = key + main + light + (outline ? 1 : 0); let c = cache.get(id); if (c) return c;
  const rows = GLYPHS[key] || GLYPHS.orb; const h = rows.length, w = Math.max(...rows.map((r) => r.length));
  c = document.createElement('canvas'); c.width = w + 2; c.height = h + 2; const x = c.getContext('2d');
  const at = (i, j) => (rows[j] && rows[j][i] && rows[j][i] !== '.' ? rows[j][i] : null);
  if (outline) { x.fillStyle = darken(main, 0.25); for (let j = -1; j <= h; j++) for (let i = -1; i <= w; i++) if (!at(i, j) && (at(i - 1, j) || at(i + 1, j) || at(i, j - 1) || at(i, j + 1))) x.fillRect(i + 1, j + 1, 1, 1); }
  for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) { const ch = at(i, j); if (!ch) continue; x.fillStyle = ch === '*' ? '#ffffff' : ch === '+' ? light : main; x.fillRect(i + 1, j + 1, 1, 1); }
  if (cache.size > 4000) cache.clear();
  cache.set(id, c); return c;
}
